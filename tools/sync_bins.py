#!/usr/bin/env python3
"""Regenerate Cargo.toml (gitignored) from Cargo.toml.template + nested .rs files."""
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "Cargo.template.toml"
CARGO_TOML = ROOT / "Cargo.toml"

SKIP_DIRS = {"target", "cmake-build-debug", "src", ".git", "IO", "Templates", "tools"}


def find_rs_files():
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for fname in filenames:
            if fname.endswith(".rs"):
                yield Path(dirpath) / fname


def build_bin_section():
    lines = []
    seen = {}
    for rs_file in sorted(find_rs_files()):
        name = rs_file.stem
        if name in seen:
            name = f"{rs_file.parent.name}_{rs_file.stem}"
        seen[name] = rs_file
        rel_path = rs_file.relative_to(ROOT).as_posix()
        lines += ["", "[[bin]]", f'name = "{name}"', f'path = "{rel_path}"']
    return "\n".join(lines)


def main():
    if not TEMPLATE.exists():
        print("Cargo.template.toml not found — create it first.")
        return

    base = TEMPLATE.read_text().rstrip()
    bin_section = build_bin_section()
    header = "# AUTO-GENERATED by tools/sync_bins.py — do not edit directly, edit Cargo.toml.template instead\n\n"
    CARGO_TOML.write_text(header + base + "\n" + bin_section + "\n")
    print(f"Cargo.toml regenerated with {bin_section.count('[[bin]]')} bin targets.")


if __name__ == "__main__":
    main()
